export function getTextColor(backgroundColor: string) {
  // Parse the hex color and convert to RGB
  const r = parseInt(backgroundColor.slice(1, 3), 16) / 255;
  const g = parseInt(backgroundColor.slice(3, 5), 16) / 255;
  const b = parseInt(backgroundColor.slice(5, 7), 16) / 255;

  // Convert to linear RGB
  const linearR = r <= 0.03928 ? r / 12.92 : Math.pow((r + 0.055) / 1.055, 2.4);
  const linearG = g <= 0.03928 ? g / 12.92 : Math.pow((g + 0.055) / 1.055, 2.4);
  const linearB = b <= 0.03928 ? b / 12.92 : Math.pow((b + 0.055) / 1.055, 2.4);

  // Calculate luminance
  const luminance = 0.2126 * linearR + 0.7152 * linearG + 0.0722 * linearB;

  // Return black or white text based on luminance threshold
  return luminance < 0.5 ? '#FFFFFF' : '#000000';
}
